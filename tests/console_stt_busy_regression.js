'use strict';
const assert=require('assert'), fs=require('fs'), vm=require('vm');
const source=fs.readFileSync('app/foundation/console/console.js','utf8');
const phone=fs.readFileSync('app/foundation/console/phone.js','utf8');
const context=vm.createContext({interactionActive:()=>true});
const helper=source.indexOf('function audioRetryText(');
if(helper>=0) vm.runInContext(source.slice(helper,source.indexOf('function outputLiveEntries(',helper)),context);
vm.runInContext(source.slice(source.indexOf('function outputLiveEntries('),source.indexOf('function eventLiveEntry(')),context);
const entry=reason=>context.outputLiveEntries({at:1,result:{outputs:[{action:'audio_retry',reason}]}})[0];
assert.match(entry('stt_busy').text,/занят|секундоч/,'busy admission has a system explanation');
assert.doesNotMatch(entry('stt_busy').text,/не расслыш|не удалось распознать|не понял/i,'busy cannot blame recognition quality');
assert.match(entry('stt_unknown').text,/не расслыш|распознать/i,'unknown speech keeps the ordinary retry');
vm.runInContext(source.slice(source.indexOf('function interactionGuide('),source.indexOf('function updateGuide(')),context);
const busy=context.audioRetryText('stt_busy');
const state={session:{state:'ACTIVE',node:'bear_dialogue',handset_up:true},simulator:{microphone:{eligible:true}}};
const hint=context.interactionGuide(state,{microphone:true,microphoneAccepting:true,audioRetry:true,audioRetryReason:'stt_busy'});
assert(hint[1].includes(busy));
assert.doesNotMatch(hint[1],/не расслыш|не понял/i);
assert.match(hint[1],/7/,'busy still advertises a button exit');
const fields={};
context.$=id=>fields[id]||(fields[id]={textContent:'',dataset:{},setAttribute(){}});
Object.assign(context,{state,simulator:state.simulator,microphoneError:'',sessionPending:null,canMutate:()=>true,
  renderInstruction(){},bridge:{media:()=>({microphone:true,microphoneAccepting:true,audioRetry:true,audioRetryMessage:busy}),updateGuide(){}}});
vm.runInContext(phone.slice(phone.indexOf('  function renderMedia()'),phone.indexOf('  function diagnostics()')),context);
context.renderMedia();
assert(fields['phone-media-status'].textContent.includes(busy),'phone surface retains the differentiated explanation');
assert.doesNotMatch(fields['phone-media-status'].textContent,/не расслыш|не понял/i);
context.bridge.media=()=>({microphone:true,microphoneAccepting:true,audioRetry:false,audioRetryMessage:''});
context.renderMedia();
assert.doesNotMatch(fields['phone-media-status'].textContent,/занят|секундоч|не расслыш/,'next successful/current state clears the old busy message');
console.log('busy admission, unknown speech, button exit, phone rendering and recovery messages passed');
