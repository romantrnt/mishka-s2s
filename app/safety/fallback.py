import random

# Черновые формулировки - уточним с нейропсихологом/заказчиком. Несколько
# вариантов нужны, чтобы редирект не звучал каждый раз одной и той же
# механической фразой.
REDIRECT_PHRASES = [
    "Давай поговорим о чём-нибудь другом. Расскажи, во что ты любишь играть?",
    "Мне вот интересно, а какое у тебя любимое животное?",
    "Давай лучше поболтаем о чём-то приятном. Как прошёл твой день?",
    "А расскажи мне про свою любимую игрушку?",
]

SILENCE_FALLBACK_PHRASES = [
    "Я не совсем расслышал. Повторишь ещё раз?",
    "Прости, не разобрал. Скажешь ещё разок?",
    "Кажется, я прослушал. Повтори, пожалуйста.",
]

# Если один и тот же звонок несколько раз подряд натыкается на BLOCK из
# "намеренных" категорий (см. SafetyCheckResult.escalates) - это, скорее
# всего, не случайность, а целенаправленное прощупывание границ. Обычный
# редирект в этом случае начинает выглядеть как бесконечное терпение и
# только поощряет пробовать ещё - поэтому реакция меняется на приглашение
# позвать взрослого, оставаясь такой же тёплой, без укоров.
ESCALATION_PHRASES = [
    "Мне кажется, сейчас будет лучше, если рядом будет взрослый. Позовёшь кого-нибудь?",
    "Давай ненадолго остановимся, и ты позовёшь кого-то из взрослых, хорошо?",
]

# Если несколько раз ПОДРЯД (см. SafetyGuard.UNCLEAR_ESCALATION_THRESHOLD) не
# получается разобрать речь ребёнка - вероятнее всего, дело в микрофоне/шуме,
# а не в том, что ребёнок специально говорит непонятно. Бесконечно повторять
# "не расслышал" в этом случае звучит как поломка устройства, поэтому дальше
# зовём взрослого - но по ДРУГОЙ причине и другими словами, чем
# ESCALATION_PHRASES выше (та эскалация - про содержание разговора, эта -
# про качество звука/устройство).
UNCLEAR_ESCALATION_PHRASES = [
    "Кажется, я никак не могу тебя расслышать. Позовёшь взрослого - может, дело в микрофоне?",
    "Мне не удаётся разобрать, что ты говоришь. Попроси, пожалуйста, взрослого посмотреть, что с трубкой.",
]

# Небольшая (3B) модель иногда вместо связной реплики выдаёт бессвязный
# обрывок вместо ответа - не потому, что не расслышала ребёнка (речь
# распознана верно), а потому что сама "споткнулась" при генерации,
# чаще всего на непривычном имени собственном (воспроизведено вживую
# 07.09.2026 - "Га-га!" в ответ на "Гарри Поттер"). Это ДРУГАЯ причина,
# чем SILENCE_FALLBACK_PHRASES (там речь ребёнка не распознана) - тут
# наоборот, признаём собственную заминку, а не намекаем, что ребёнок
# сказал что-то непонятное.
CONFUSED_FALLBACK_PHRASES = [
    "Ой, что-то я задумался. О чём мы говорили?",
    "Прости, я немного запутался в мыслях. Давай ещё раз?",
]


class FallbackPhrases:
    """ Пул фраз для редиректа/fallback: выбирает случайную, не повторяя последнюю подряд """

    def __init__(self, phrases: list[str]):
        self._phrases = phrases
        self._last: str | None = None

    def pick(self) -> str:
        choices = [p for p in self._phrases if p != self._last] or self._phrases
        phrase = random.choice(choices)
        self._last = phrase
        return phrase
