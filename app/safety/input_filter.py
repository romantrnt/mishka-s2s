import re

from app.safety.severity import SafetyAction, SafetyCheckResult

# Черновые формулировки и список тем - уточняются у заказчика и с
# нейропсихологом (точные требования ожидаются через пару дней после
# 01.09.2026). Список намеренно узкий: бытовые темы про здоровье и боль -
# нормальный разговор в реабилитационном центре, их не блокируем, с ними
# справляется системный промпт.
DANGEROUS_PATTERNS: dict[str, re.Pattern] = {
    "weapons_drugs_self_harm": re.compile(
        r"как[^.!?]{0,20}сделать[^.!?]{0,20}(бомбу|оружие|пистолет)"
        r"|где[^.!?]{0,20}достать[^.!?]{0,20}наркотик"
        r"|как[^.!?]{0,20}себя[^.!?]{0,20}порезать"
        r"|как[^.!?]{0,20}навредить[^.!?]{0,20}себе",
        re.IGNORECASE,
    ),
    # Прямая попытка сломать промпт + попытки через ролевую игру ("притворись
    # кем-то другим", "выйди из роли") - маленькие модели заметно хуже
    # сопротивляются именно ролевым обходам, чем большие.
    # 2026-09-03: было "\s+" между глаголом и объектом - слетало на любой
    # вставке между ними ("Притворись, что...", "Сыграй, пожалуйста, роль",
    # "Выйди, наконец, из роли"), т.к. запятая/лишнее слово не совпадали
    # с "ровно один пробел". Заменено на "[^.!?]{0,20}" - допускает
    # короткую вставку в пределах того же предложения, но не убегает в
    # соседние фразы.
    "prompt_injection": re.compile(
        r"игнорируй[^.!?]{0,20}(инструкции|правила)"
        r"|забудь[^.!?]{0,20}(инструкции|правила|мишка)"
        r"|какой\s+у\s+тебя\s+промпт"
        r"|покажи\s+(свой\s+)?промпт"
        r"|ты\s+на\s+самом\s+деле"
        r"|притворись"
        r"|представь[^.!?]{0,20}что\s+ты"
        r"|сыграй[^.!?]{0,20}роль"
        r"|выйди[^.!?]{0,20}роли"
        r"|ты\s+не\s+мишка",
        re.IGNORECASE,
    ),
}

# Сигналы бедствия: НЕ блокируем, пропускаем в LLM (промпт уже отвечает на
# это тепло - "признать + предложить позвать взрослого"), только логируем,
# чтобы взрослые в центре могли отреагировать уже вживую.
DISTRESS_PATTERNS: dict[str, re.Pattern] = {
    "distress_signal": re.compile(
        r"мне\s+страшно"
        r"|меня\s+бьют"
        r"|меня\s+обижают"
        r"|хочу\s+умереть"
        r"|не\s+хочу\s+жить",
        re.IGNORECASE,
    ),
}


class InputSafetyFilter:
    """ Проверка текста ребёнка до вызова LLM """

    def check(self, text: str) -> SafetyCheckResult:

        for category, pattern in DANGEROUS_PATTERNS.items():
            if pattern.search(text):
                return SafetyCheckResult(
                    SafetyAction.BLOCK,
                    category=category,
                    matched_text=text,
                    escalates=True,
                )

        for category, pattern in DISTRESS_PATTERNS.items():
            if pattern.search(text):
                return SafetyCheckResult(
                    SafetyAction.LOG_ONLY,
                    category=category,
                    matched_text=text,
                )

        return SafetyCheckResult(SafetyAction.ALLOW)
