def normalize_band(band: str) -> str:
    """Map historical profile bands onto the exhibition's three age bands."""
    value = {'3-5': '4-5', '5-7': '6-7'}.get(str(band), str(band))
    if value not in BANDS:
        raise ValueError('unknown age band')
    return value


