def _odd_bank(band: str) -> tuple[GameChallenge, ...]:
    return tuple(
        GameChallenge(f'odd-{band}-{index:02d}', 'odd_one_out', band,
                      f'Найди лишнее. Четыре варианта — {category}.',
                      tuple(enumerate((*members.split('|'), outsider), 1)), 5,
                      (f'Ищем то, что не подходит к группе: {category}.',
                       f'Лишний вариант — {outsider}.'),
                      display='colors' if band == '1-3' else 'digits')
        for index, (category, members, outsider) in enumerate(_ODD_ROWS[band], 1)
    )


def _color(index: str, band: str, prompt: str, answer: int,
           choices: tuple[int, ...] = (1, 2, 3, 4, 5, 6, 7)) -> GameChallenge:
    name = dict(COLORS)[answer]
    return GameChallenge(f'quiz-{band}-{index}', 'quiz', band, prompt,
                         tuple((key, text) for key, text in COLORS if key in choices),
                         answer, (f'Нужен {name} цвет.', f'Нажми {name} огонёк.'),
                         display='colors')


def _icon(index: str, band: str, prompt: str, answer: int) -> GameChallenge:
    text = 'мишка' if answer == 6 else 'значок погоды'
    return GameChallenge(f'quiz-{band}-{index}', 'quiz', band, prompt,
                         ((answer, text),), answer,
                         (f'Посмотри, где {text}.', f'Нажми подсвеченный {text}.'),
                         display='pictograms')


def _question(index: str, band: str, prompt: str, options: str,
              answer: int, hint: str, phrase_id: str | None = None) -> GameChallenge:
    pairs = tuple((int(part.split(':', 1)[0]), part.split(':', 1)[1])
                  for part in options.split('|'))
    return GameChallenge(f'quiz-{band}-{index}', 'quiz', band, prompt, pairs,
                         answer, (hint, f'Правильный вариант: {dict(pairs)[answer]}.'),
                         phrase_id=phrase_id)


