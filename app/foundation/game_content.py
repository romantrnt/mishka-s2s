def _adjacent_pool(kind: str, band: str) -> tuple[GameChallenge, ...]:
    if band == '1-3':
        # A toddler's adjacent material remains concrete, familiar and nonnumeric.
        if kind == 'quiz':
            return tuple(item for item in _QUIZ_MIDDLE[:7] if item.display == 'colors')
        return tuple(item for item in _BANKS[kind]['4-5']
                     if item.id.rsplit('-', 1)[1] in {'10', '11', '12', '17', '19', '20', '21', '24', '29', '35', '38', '45', '46'})
    if band == '4-5':
        if kind == 'quiz':
            return (*_QUIZ_YOUNG[:7], *(_QUIZ_OLDER[index - 1] for index in (5, 8, 21, 22, 23)))
        return (*_BANKS[kind]['1-3'], *(_BANKS[kind]['6-7'][index - 1]
                                     for index in (9, 10, 11, 12, 14, 15, 18, 19, 20, 45, 46, 50)))
    return _BANKS[kind]['4-5']


def build_deck(kind: str, age_band: str, *, seed: int) -> tuple[GameChallenge, ...]:
    """Build a deterministic shuffled deck, with about 17% adjacent material.

    ``age_band`` records the source difficulty of a challenge. Every primary
    challenge appears once; only a bounded sample of an adjacent band is added.
    A new seed on menu entry creates a new order and odd-option assignment.
    """
    if kind not in _BANKS:
        raise ValueError('unknown game kind')
    band = normalize_band(age_band)
    rng = random.Random(seed)
    primary = _BANKS[kind][band]
    adjacent = _adjacent_pool(kind, band)
    count = min(len(adjacent), max(1, round(len(primary) / 5)))
    deck = [*primary, *rng.sample(adjacent, count)]
    if kind == 'odd_one_out':
        randomized = []
        for item in deck:
            answer_text = dict(item.options)[item.answer]
            values = [text for _, text in item.options]
            rng.shuffle(values)
            options = tuple(enumerate(values, 1))
            answer = next(button for button, text in options if text == answer_text)
            randomized.append(replace(item, options=options, answer=answer,
                                      display='colors' if band == '1-3' else 'digits'))
        deck = randomized
    rng.shuffle(deck)
    return tuple(deck)
