def _odd_bank(band: str) -> tuple[GameChallenge, ...]:
    return tuple(
        GameChallenge(f'odd-{band}-{index:02d}', 'odd_one_out', band,
                      f'Найди лишнее. Четыре варианта — {category}.',
                      tuple(enumerate((*members.split('|'), outsider), 1)), 5,
                      (f'Ищем то, что не подходит к группе: {category}.',
                       f'Лишний вариант — {outsider}.'),
                      display='colors' if band == '1-3' else 'digits')
        for index, (category, members, outsider) in enumerate(_ODD_ROWS[band], 1)
    )


_DIGITS = ((1, 'один'), (2, 'два'), (3, 'три'), (4, 'четыре'), (5, 'пять'), (6, 'шесть'), (7, 'семь'))


def _color(index: str, band: str, prompt: str, answer: int,
           choices: tuple[int, ...] = (1, 2, 3, 4, 5, 6, 7),
           hint: str | None = None) -> GameChallenge:
    name = dict(COLORS)[answer]
    first_hint = hint or 'Осталось три огонька — выбери нужный цвет.'
    return GameChallenge(f'quiz-{band}-{index}', 'quiz', band, prompt,
                         tuple((key, text) for key, text in COLORS if key in choices),
                         answer, (first_hint, f'Поищи {name} огонёк.'),
                         display='colors')


def _digits(index: str, band: str, prompt: str, answer: int,
            hint: str, phrase_id: str | None = None) -> GameChallenge:
    return GameChallenge(f'quiz-{band}-{index}', 'quiz', band, prompt, _DIGITS,
                         answer, (hint, f'Посчитай ещё раз: правильная цифра от одного до семи.'),
                         display='digits', phrase_id=phrase_id)


