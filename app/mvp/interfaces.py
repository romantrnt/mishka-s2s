from __future__ import annotations

from typing import Protocol

from .types import HardwareEvent, IntentResult


class IntentClassifier(Protocol):
    def classify(self, text: str) -> IntentResult: ...


class ProfileProvider(Protocol):
    def get_by_tag(self, tag_id: str): ...
    def record_game(self, child_id: str, game_id: str, success: bool) -> None: ...
    def record_story(self, child_id: str, story_id: str) -> None: ...


class HardwareAdapter(Protocol):
    def parse(self, payload: dict) -> HardwareEvent: ...
    def send(self, command: dict) -> None: ...


class LEDController(Protocol):
    def show(self, pattern: str, color: str = "yellow", duration_ms: int = 800) -> dict: ...
    def clear(self) -> dict: ...


class AudioOutput(Protocol):
    def speak(self, response_id: str, text: str, audio_asset: str | None, token: int) -> dict | None: ...
    def cancel(self, token: int) -> None: ...
    def clear(self) -> None: ...
