#!/usr/bin/env bash
set -Eeuo pipefail

ROOT="${1:-$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)}"
ROOT="$(cd "$ROOT" && pwd)"
VENV="${VENV:-$ROOT/.venv}"
CACHE_ROOT="${MISHKA_CACHE_ROOT:-/workspace/.cache/mishka}"
ENV_FILE="${MISHKA_ENV_FILE:-/workspace/.config/mishka/.env.runpod}"
BASE_IMAGE="${BASE_IMAGE:-runpod/pytorch:1.0.2-cu1281-torch280-ubuntu2404}"

if [[ -r "$ENV_FILE" ]]; then
  set -a
  # shellcheck disable=SC1090
  . "$ENV_FILE"
  set +a
fi

abs_path() {
  case "$1" in
    /*) printf '%s' "$1" ;;
    *) printf '%s/%s' "$ROOT" "$1" ;;
  esac
}

SILERO_CACHE="$(abs_path "${SILERO_CACHE_PATH:-$CACHE_ROOT/silero/v5_5_ru.pt}")"
RVC_MODEL="$(abs_path "${RVC_MODEL:-models/rvc/mishka_rvc_v2_e250_2250s.pth}")"
RVC_INDEX="$(abs_path "${RVC_INDEX:-models/rvc/mishka_rvc_v2_e250_2250s.index}")"
RVC_PROJECT_ROOT="$(abs_path "${RVC_PROJECT_ROOT:-vendor/rvc}")"
[[ -s "$SILERO_CACHE" ]] || { echo "ERROR: Silero cache missing: $SILERO_CACHE" >&2; exit 1; }
[[ -s "$RVC_MODEL" ]] || { echo "ERROR: canonical RVC model missing: $RVC_MODEL" >&2; exit 1; }
[[ -s "$RVC_INDEX" ]] || { echo "ERROR: canonical RVC index missing: $RVC_INDEX" >&2; exit 1; }
[[ -x "$VENV/bin/python" ]] || { echo "ERROR: Python venv missing: $VENV" >&2; exit 1; }

MODEL_SHA256="$(sha256sum "$RVC_MODEL" | awk '{print $1}')"
INDEX_SHA256="$(sha256sum "$RVC_INDEX" | awk '{print $1}')"
PYTHON_VERSION="$("$VENV/bin/python" -c 'import sys; print(sys.version.split()[0])')"
TORCH_VERSION="$("$VENV/bin/python" -c 'import torch; print(torch.__version__)')"
CUDA_VERSION="$("$VENV/bin/python" -c 'import torch; print(torch.version.cuda)')"
DRIVER_VERSION="${DRIVER_VERSION:-unknown}"

cat > "$ROOT/.bootstrap-contract" <<EOF_CONTRACT
# Generated by scripts/generate_bootstrap_contract.sh; do not edit by hand.
IMAGE=$BASE_IMAGE
PROJECT_ROOT=$ROOT
PYTHON=$PYTHON_VERSION
TORCH=$TORCH_VERSION
CUDA=$CUDA_VERSION
NVIDIA_DRIVER=$DRIVER_VERSION
WHISPER_MODEL=${WHISPER_MODEL:-large-v3-turbo}
LLM_MODEL=${LLM_MODEL:-qwen3:14b}
SILERO_MODEL=${SILERO_MODEL:-v5_5_ru}
SILERO_SPEAKER=${SILERO_SPEAKER:-aidar}
SILERO_CACHE_PATH=$SILERO_CACHE
RVC_RELEASE=mishka_rvc_v2_e250_2250s
RVC_PROJECT_ROOT=$RVC_PROJECT_ROOT
RVC_MODEL=$RVC_MODEL
RVC_INDEX=$RVC_INDEX
RVC_MODEL_SHA256=$MODEL_SHA256
RVC_INDEX_SHA256=$INDEX_SHA256
RVC_F0_UP_KEY=${RVC_F0_UP_KEY:-0}
RVC_INDEX_RATE=${RVC_INDEX_RATE:-0.0}
RVC_PROTECT=${RVC_PROTECT:-0.33}
RVC_FALLBACK_MODE=${RVC_FALLBACK_MODE:-fail_closed}
RVC_STARTUP_TIMEOUT_SECONDS=${RVC_STARTUP_TIMEOUT_SECONDS:-60}
OLLAMA_MODELS=${OLLAMA_MODELS:-$CACHE_ROOT/ollama}
EOF_CONTRACT

echo "Bootstrap contract generated: $ROOT/.bootstrap-contract"
